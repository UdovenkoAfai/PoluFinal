#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
import random
import shutil
import sys
from pathlib import Path

import cv2

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from generator.plate_render import random_plate_number, render_plate, render_other, paste_plate_scene

FIELDNAMES = [
    "image", "plate_num", "plate_type", "bbox", "quad",
    "is_vehicle", "is_synthetic", "source", "license", "conditions"
]


def quad_to_bbox(quad):
    xs = [int(round(p[0])) for p in quad]
    ys = [int(round(p[1])) for p in quad]
    x1, x2 = min(xs), max(xs)
    y1, y2 = min(ys), max(ys)
    return x1, y1, x2 - x1, y2 - y1


def encode_quad(quad):
    vals = []
    for x, y in quad:
        vals.extend([str(int(round(x))), str(int(round(y)))])
    return ",".join(vals)


def generate(out_dir: Path, count: int, seed: int, clean: bool, image_quality: int = 78, canvas_size=(640, 360)):
    rng = random.Random(seed)
    syn_dir = out_dir / "images" / "synthetic"
    real_dir = out_dir / "images" / "real"
    labels_dir = out_dir / "labels"
    meta_path = out_dir / "meta.csv"
    real_rows = []
    if meta_path.exists():
        try:
            with meta_path.open(encoding="utf-8-sig", newline="") as f:
                reader = csv.DictReader(f, delimiter=";")
                real_rows = [r for r in reader if r.get("is_synthetic") == "0"]
        except Exception:
            real_rows = []

    if clean and out_dir.exists():
        if syn_dir.exists():
            shutil.rmtree(syn_dir)
        if labels_dir.exists():
            for lp in labels_dir.glob("synthetic_*.txt"):
                lp.unlink()
    syn_dir.mkdir(parents=True, exist_ok=True)
    real_dir.mkdir(parents=True, exist_ok=True)
    labels_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    for i in range(count):
        r = rng.random()
        if r < 0.30:
            plate_type = "type1a"
        elif r < 0.60:
            plate_type = "type1b"
        elif r < 0.90:
            plate_type = "type1"
        else:
            plate_type = "other"

        if plate_type == "other":
            plate_im, _ = render_other(rng)
            plate_num = "########"
            is_vehicle = 1 if rng.random() < 0.8 else 0
        else:
            plate_num = random_plate_number(rng)
            plate_im = render_plate(plate_num, plate_type, rng)
            is_vehicle = 1

        scene, quad, conditions = paste_plate_scene(plate_im, rng, canvas_size=canvas_size)
        if not is_vehicle:
            conditions.append("screen")

        name = f"synthetic_{i:06d}.jpg"
        rel = f"images/synthetic/{name}"
        img_path = syn_dir / name
        cv2.imwrite(str(img_path), scene, [int(cv2.IMWRITE_JPEG_QUALITY), image_quality])

        x, y, w, h = quad_to_bbox(quad)
        row = {
            "image": rel,
            "plate_num": plate_num,
            "plate_type": plate_type,
            "bbox": f"{x},{y},{w},{h}",
            "quad": encode_quad(quad),
            "is_vehicle": str(is_vehicle),
            "is_synthetic": "1",
            "source": "generated_by_participant",
            "license": "CC BY 4.0",
            "conditions": ",".join(dict.fromkeys(conditions)),
        }
        rows.append(row)

        with (labels_dir / f"synthetic_{i:06d}.txt").open("w", encoding="utf-8") as f:
            f.write(";".join(row[k] for k in FIELDNAMES) + "\n")

    with meta_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES, delimiter=";")
        writer.writeheader()
        writer.writerows(real_rows)
        writer.writerows(rows)

    readme = out_dir / "README.md"
    if not readme.exists():
        readme.write_text(
            "# Dataset\n\nSynthetic data are generated by `generator/generate_dataset.py`. "
            "Place legally obtained real images in `images/real/` and append their metadata to `meta.csv`.\n",
            encoding="utf-8",
        )
    (out_dir / "LICENSE").write_text(
        "Dataset submission is intended for release under Creative Commons Attribution 4.0 (CC BY 4.0).\n"
        "Only add real materials whose licenses permit redistribution under the submission terms.\n",
        encoding="utf-8",
    )
    print(f"Generated {count} synthetic images in {syn_dir}")
    print(f"Metadata: {meta_path}")


def main():
    p = argparse.ArgumentParser(description="Generate a reproducible synthetic Russian license-plate dataset")
    p.add_argument("--out", type=Path, default=ROOT / "dataset")
    p.add_argument("--count", type=int, default=5000)
    p.add_argument("--seed", type=int, default=20260926)
    p.add_argument("--clean", action="store_true", help="replace synthetic images and labels")
    p.add_argument("--quality", type=int, default=78)
    p.add_argument("--width", type=int, default=640)
    p.add_argument("--height", type=int, default=360)
    args = p.parse_args()
    generate(args.out, args.count, args.seed, args.clean, args.quality, (args.width, args.height))


if __name__ == "__main__":
    main()
